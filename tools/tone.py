WORD = re.compile("(" + "|".join(sorted(M, key=len, reverse=True)) + r")(?=[.\s]|$)")
FENCE = re.compile(r"^```")


def convert(line):
    return WORD.sub(lambda m: M[m.group(1)], line)


PLAIN = re.compile(r"[가-힣]+(?<!니)다(?=[.\s]|$)")


def report(path, start):
    """아직 평서형으로 남은 낱말을 센다. 표에 없어서 안 바뀐 것들이다."""
    import collections
    raw = open(path, encoding="utf-8").read()
    body = re.sub(r"```.*?```", "", raw[raw.index(start):], flags=re.S)
    left = collections.Counter()
    for line in body.split("\n"):
        if line.startswith("#") or line.lstrip().startswith("- ["):
            continue
        for seg in re.split(r"(?<=다[.])\s+|\|", line):
            seg = seg.strip().rstrip(".").strip()
            m = PLAIN.search(seg)
            if seg and m and m.end() == len(seg):
                left[m.group(0)] += 1
    for w, c in left.most_common():
        print(f"{c:4} {w}")
    print(f"     — 남은 문장 {sum(left.values())}")


def main(path, start):
    src = open(path, encoding="utf-8").read()
    head, body = src[:src.index(start)], src[src.index(start):]
    out, fence, diag = [], False, False
    for line in body.split("\n"):
        if FENCE.match(line):
            diag = not fence and line.startswith("```labdiagram")
            fence = not fence
            out.append(line)
            continue
        if line.startswith("#") or line.startswith("|---"):
            out.append(line)
            continue
        if fence and not (diag and re.match(r"^  - [^{]", line)):
            out.append(line)
            continue
        out.append(convert(line))
    open(path, "w", encoding="utf-8").write(head + "\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) == 4 and sys.argv[3] == "--report":
        report(sys.argv[1], sys.argv[2])
    elif len(sys.argv) == 3:
        main(sys.argv[1], sys.argv[2])
    else:
        sys.exit("usage: python3 tools/tone.py <파일> '<이 문자열부터>' [--report]")
